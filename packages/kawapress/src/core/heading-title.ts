import type { Token } from 'markdown-exit'

/**
 * Inline token types that only describe formatting. Their markup is dropped,
 * so `**bold**`, `*emphasis*`, `~~gone~~` and `[link](/guide)` keep the words
 * their author wrote and nothing else.
 */
const FORMATTING_MARKUP_TYPES = new Set([
  'em_open',
  'em_close',
  'strong_open',
  'strong_close',
  's_open',
  's_close',
  'link_open',
  'link_close',
])

/**
 * The plain-text title of a heading: the text its author wrote on the heading
 * line, without the Markdown formatting markup.
 *
 * Formatting markup disappears while its text stays, inline code keeps its
 * content without the backticks, and anything that is not plain formatting
 * keeps the markup it was written with, so inline math stays `$E=mc^2$`,
 * inline HTML stays `<kbd>`, and an emoji shortcode stays `:smile:`. A token
 * type this function has never seen keeps its `content` too, so a Markdown
 * plugin can never make heading text disappear, and the title of a page never
 * depends on which plugins a site installed.
 */
export function resolveHeadingTitle(inline: Token): string {
  return collapseWhitespace(readPlainText(inline.children ?? []))
}

function readPlainText(children: readonly Token[]): string {
  let text = ''
  for (const child of children) {
    text += readTokenText(child)
  }
  return text
}

function readTokenText(token: Token): string {
  // The permalink symbol is generated by KawaPress, not written by the author.
  if (FORMATTING_MARKUP_TYPES.has(token.type) || token.meta?.isPermalinkSymbol) {
    return ''
  }

  // Tokens that carry child tokens, such as the alt text of an image, are
  // plain text of their own and never the markup around them.
  const children = token.children ?? []
  if (children.length > 0) {
    return readPlainText(children)
  }

  if (token.type === 'softbreak' || token.type === 'hardbreak') {
    return ' '
  }

  // Plain text is already what the reader sees: entities and escapes are
  // decoded into `content`, and `markup` only records how they were written.
  if (token.type === 'text' || token.type === 'code_inline') {
    return token.content
  }

  // An inline container this function does not know keeps the markup it opens
  // or closes with, for example `==` around highlighted text.
  if (token.nesting !== 0) {
    return token.markup
  }

  // Any other extension markup surrounds its text, for example `$a+b$`.
  return token.markup ? `${token.markup}${token.content}${token.markup}` : token.content
}

function collapseWhitespace(text: string): string {
  return text.replace(/\s+/g, ' ').trim()
}
